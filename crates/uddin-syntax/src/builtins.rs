pub(crate) fn is_builtin(name: &str) -> bool {
    BUILTIN_TABLE.binary_search(&name).is_ok()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn sorted_and_unique() {
        assert!(BUILTIN_TABLE.windows(2).all(|w| w[0] < w[1]));
        assert_eq!(
            BUILTIN_TABLE
                .iter()
                .filter(|n| n.starts_with("waf_"))
                .count(),
            17
        );
        assert!(is_builtin("read_file") && is_builtin("import") && !is_builtin("my_var"));
    }
}
